WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
  existing_objects NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER') IN ('SYS','SYSTEM','ADMIN') THEN
    RAISE_APPLICATION_ERROR(-20001,'Use a dedicated demo schema');
  END IF;
  SELECT COUNT(*) INTO existing_objects FROM USER_OBJECTS
  WHERE OBJECT_NAME IN ('EMP','DEPT');
  IF existing_objects > 0 THEN
    RAISE_APPLICATION_ERROR(-20001,'EMP or DEPT already exists; inspect and reuse it instead');
  END IF;
END;
/
CREATE TABLE DEPT (
  DEPTNO NUMBER(2) CONSTRAINT PK_DEPT PRIMARY KEY,
  DNAME VARCHAR2(14),
  LOC VARCHAR2(13)
);
CREATE TABLE EMP (
  EMPNO NUMBER(4) CONSTRAINT PK_EMP PRIMARY KEY,
  ENAME VARCHAR2(10),
  JOB VARCHAR2(9),
  MGR NUMBER(4),
  HIREDATE DATE,
  SAL NUMBER(7,2),
  COMM NUMBER(7,2),
  DEPTNO NUMBER(2) CONSTRAINT FK_EMP_DEPT REFERENCES DEPT(DEPTNO)
);
