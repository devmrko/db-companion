import {build} from 'esbuild';
import {readFile, writeFile, mkdir, readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../src/main/resources/static/vendor/ontology-flow');
const result = await build({absWorkingDir: here, entryPoints: ['ontology-flow.jsx'], bundle: true,
  outfile: path.join(out, 'ontology-flow.js'), format: 'esm', target: 'es2022', minify: true,
  define: {'process.env.NODE_ENV': '"production"'}, legalComments: 'eof', write: false, metafile: true});
const modules = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (match) modules.add(match[1]);
}
let notices = 'Bundled dependencies — generated by frontend/build.mjs\n\n';
for (const name of [...modules].sort()) {
  const dir = path.join(here, 'node_modules', name), pkg = JSON.parse(await readFile(path.join(dir,'package.json'),'utf8'));
  notices += `\n${name} ${pkg.version} — ${pkg.license}\n${pkg.repository?.url || pkg.repository || ''}\n`;
  const licenses = (await readdir(dir)).filter(n => /^(license|copying|notice)/i.test(n));
  if (!licenses.length) throw new Error('License missing: ' + name);
  for (const file of licenses) notices += '\n' + await readFile(path.join(dir,file),'utf8') + '\n';
}
notices += '\nELK source: https://github.com/kieler/elkjs/tree/v0.12.1 (unmodified npm distribution).\n';
const outputs = [...result.outputFiles.map(f => [f.path, f.contents]), [path.join(out,'THIRD-PARTY-NOTICES.txt'), Buffer.from(notices)]];
await mkdir(out, {recursive: true});
for (const [file, bytes] of outputs) {
  if (process.argv.includes('--check')) {
    if (!Buffer.from(await readFile(file)).equals(Buffer.from(bytes))) throw new Error('Stale bundle: '+path.basename(file));
  } else await writeFile(file, bytes);
}
console.log(process.argv.includes('--check') ? 'Graph bundle verified.' : 'Graph bundle and licenses built.');
