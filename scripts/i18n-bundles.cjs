// Regenerate UTF-8 bundles from the reviewed UI inventory and translations.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const rows=JSON.parse(fs.readFileSync(path.join(root,'tools/i18n/catalog.json'),'utf8'));
const translations={};
const features=JSON.parse(fs.readFileSync(path.join(root,'tools/i18n/vector-oci.json'),'utf8'));
for(const file of fs.readdirSync(path.join(root,'tools/i18n')).filter(n=>/^feature-.*\.json$/.test(n)).sort())
  Object.assign(features,JSON.parse(fs.readFileSync(path.join(root,'tools/i18n',file),'utf8')));
for(const file of fs.readdirSync(path.join(root,'tools/i18n')).filter(n=>/^\d.*\.json$/.test(n)))
  Object.assign(translations,JSON.parse(fs.readFileSync(path.join(root,'tools/i18n',file),'utf8')));
const escape=s=>s.replaceAll('\\','\\\\').replaceAll('\n','\\n').replaceAll('\r','\\r').replaceAll('\t','\\t').replace(/^ /,'\\ ').replace(/ +$/g,spaces=>'\\u0020'.repeat(spaces.length));
for(const [language,index]of [['',-1],['ko',-1],['en',0],['zh_CN',1],['ja',2]]){
  const content=rows.map((r,i)=>`${r.key}=${escape(index<0?r.ko:(translations[i]?.[index]??r.ko))}`).join('\n');
  const unsaved=['언어를 바꾸면 입력 중인 내용이 사라집니다. 계속할까요?','Changing language will discard unsaved input. Continue?','切换语言将丢失未保存的输入。是否继续？','言語を変更すると未保存の入力が失われます。続行しますか？'][index+1];
  fs.writeFileSync(path.join(root,`src/main/resources/i18n/messages${language?'_'+language:''}.properties`),'# UTF-8 UI messages. Generated by scripts/i18n-bundles.cjs\n'+content+'\nlanguage.unsaved='+unsaved+'\n');
  const common={
    'language.label':['언어','Language','语言','言語'],
    'language.apply':['언어 적용','Apply language','应用语言','言語を適用'],
    'nav.workspace':['워크스페이스','Workspace','工作区','ワークスペース']
  };
  fs.appendFileSync(path.join(root,`src/main/resources/i18n/messages${language?'_'+language:''}.properties`),Object.entries(common).map(([key,values])=>key+'='+values[index+1]).join('\n')+'\n');
  fs.appendFileSync(path.join(root,`src/main/resources/i18n/messages${language?'_'+language:''}.properties`),Object.entries(features).map(([key,values])=>key+'='+escape(values[index+1])).join('\n')+'\n');
}
console.log(JSON.stringify({total:rows.length,translated:Object.keys(translations).length,pending:rows.length-Object.keys(translations).length}));
